//  esc.js — หลบอักขระ HTML (ตัวเดียวทั้งระบบ · รายงานความปลอดภัย F-04)
//  ใช้ทุกครั้งที่ใส่ข้อความจากผู้ใช้/ฐานข้อมูลลงใน innerHTML หรือค่า attribute
//  หลบครบ 5 ตัว: & < > " '  (ใช้ได้ทั้งใน attribute แบบ "…" และ '…')
// =====================================================================
const MAP = { "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" };
export const esc = (s) => String(s ?? "").replace(/[&<>"']/g, (c) => MAP[c]);
